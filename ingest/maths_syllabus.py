def S(code, title, objectives, concepts, formulas, method, mistakes, connections, recall):
    return {"code": code, "title": title, "level": "AHL" if _ahl(code) else "SL", "objectives": objectives, "concepts": concepts,
            "formulas": [{"name": f[0], "tex": f[1], "where": f[2], "when": f[3] if len(f) > 3 else ""} for f in formulas],
            "method": method, "mistakes": mistakes, "connections": connections,
            "recall": [{"q": q, "a": a} for q, a in recall]}


def _ahl(code: str) -> bool:
    t, s = map(int, code.split("."))
    return s > {1: 8, 2: 6, 3: 6, 4: 11, 5: 8}[t]


